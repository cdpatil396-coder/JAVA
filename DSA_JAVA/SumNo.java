import java.util.Scanner;
class SumNo{
    public static void main(String args[]){
        Scanner sc = new Scanner(System.in);
        System.out.println("Enter first and second num: ");
        int a =sc.nextInt();
        int b =sc.nextInt();
        int sum = a+b;
        System.out.println("Sum of two numbers is: "+sum);

    }
}   